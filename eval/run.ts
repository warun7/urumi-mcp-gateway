/**
 * Tool-search evaluation, for the "handling many tools" stand-out. Runs against the live gateway and measures:
 *   1. Context cost: what tools/list puts in front of the model in full mode vs search mode.
 *   2. Retrieval quality of gateway__search_tools on the dev and held-out task sets (hit@1/3/5, MRR),
 *      next to a naive keyword-overlap baseline over the same catalog.
 * Writes eval/RESULTS.md and refreshes eval/catalog.snapshot.json (used by offline.ts and the CI regression test).
 *   make eval     (or: cd e2e && BASE_URL=... ADMIN_EMAIL=... ADMIN_PASSWORD=... pnpm exec tsx ../eval/run.ts)
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { Dashboard, mcpConnect } from '../e2e/lib/api.js';
import { expander, here, keywordBaseline, loadTasks, metrics, rank, tableRow, type Scored, type SetName, type Task } from './lib.js';

const BASE = process.env.BASE_URL ?? 'http://app.127.0.0.1.nip.io';
const tokens = (bytes: number) => Math.round(bytes / 4); // rough: ~4 bytes of JSON per token
const kb = (bytes: number) => `${(bytes / 1024).toFixed(1)} KB`;

const admin = new Dashboard(BASE);
await admin.login(process.env.ADMIN_EMAIL!, process.env.ADMIN_PASSWORD!);
const mkKey = async (toolMode: string) => (await admin.post('/keys', { name: `eval ${toolMode} ${Date.now().toString(36)}`, toolMode })).data.key as string;
const [fullKey, searchKey] = [await mkKey('full'), await mkKey('search')];
const full = await mcpConnect(`${BASE}/mcp`, fullKey);
const search = await mcpConnect(`${BASE}/mcp`, searchKey);

try {
  // 1. Context cost of the tool list itself.
  const fullList = (await full.listTools(undefined, { cacheMode: 'refresh' })).tools;
  const searchList = (await search.listTools(undefined, { cacheMode: 'refresh' })).tools;
  const catalog = fullList.filter((t) => !t.name.startsWith('gateway__'));
  const names = new Set(catalog.map((t) => t.name));
  const servers = (await admin.get('/servers')).data.servers as { slug: string; displayName: string }[];
  writeFileSync(join(here, 'catalog.snapshot.json'), JSON.stringify({ tools: fullList, servers: servers.map((s) => ({ slug: s.slug, displayName: s.displayName })) }));
  const stores = [...names].filter((n) => n.endsWith('__get_store_info')).length;
  const serverCount = new Set(catalog.map((t) => t.name.split('__')[0])).size;

  // 2. Retrieval, through the real MCP path.
  const expand = expander(names);
  const base = keywordBaseline(catalog);
  const results: Record<SetName, { bm25: Scored[]; kw: Scored[]; skipped: number }> = { dev: { bm25: [], kw: [], skipped: 0 }, holdout: { bm25: [], kw: [], skipped: 0 } };
  const latencies: number[] = [];
  const sizes: number[] = [];
  for (const set of ['dev', 'holdout'] as SetName[]) {
    for (const task of loadTasks(set)) {
      const expected = expand(task);
      if (!expected.size) { results[set].skipped++; continue; } // e.g. a named store that isn't provisioned here
      const t0 = performance.now();
      const r = await search.callTool({ name: 'gateway__search_tools', arguments: { query: task.q, limit: 10 } });
      latencies.push(performance.now() - t0);
      const r5 = await search.callTool({ name: 'gateway__search_tools', arguments: { query: task.q } });
      sizes.push(JSON.stringify(r5.content).length);
      results[set].bm25.push({ task, expected, got: ((r.structuredContent as any)?.results ?? []).map((x: any) => x.name as string) });
      results[set].kw.push({ task, expected, got: base(task.q) });
    }
  }

  latencies.sort((a, b) => a - b);
  const p = (q: number) => latencies[Math.min(latencies.length - 1, Math.floor(q * latencies.length))]!.toFixed(0);
  const fullBytes = JSON.stringify(fullList).length;
  const searchBytes = JSON.stringify(searchList).length;
  const avg5 = Math.round(sizes.reduce((a, b) => a + b, 0) / sizes.length);
  const dev = results.dev.bm25;
  const groups: [string, (t: Task) => boolean][] = [
    ['paraphrased (avoid the tool\'s own words)', (t) => t.tags.includes('paraphrase')],
    ['store tools (several stores expose the same tools)', (t) => t.tags.includes('store')],
    ['288-tool synthetic SaaS farm', (t) => t.tags.includes('farm')],
  ];
  const misses = dev.filter((s) => rank(s.got, s.expected) > 5);
  const header = ['| | n | hit@1 | hit@3 | hit@5 | MRR |', '|---|---|---|---|---|---|'];

  const md = [
    '# Tool-search evaluation',
    '',
    `Generated by \`eval/run.ts\` against the live gateway on ${new Date().toISOString().slice(0, 10)}. ` +
      `Catalog: **${catalog.length} tools from ${serverCount} servers** (${stores} WooCommerce stores, the fetch server, the test servers, and a 288-tool synthetic SaaS farm).`,
    '',
    '## What the model has to read',
    '',
    '| | tools/list | size | ≈ tokens (bytes ÷ 4) |',
    '|---|---|---|---|',
    `| full mode | ${fullList.length} tools | ${kb(fullBytes)} | ${tokens(fullBytes).toLocaleString('en')} on every model call |`,
    `| search mode | ${searchList.length} tools (${searchList.map((t) => `\`${t.name}\``).join(', ')}) | ${kb(searchBytes)} | ${tokens(searchBytes).toLocaleString('en')} |`,
    `| + one \`gateway__search_tools\` result (5 tools with schemas) | | ${kb(avg5)} avg | ${tokens(avg5).toLocaleString('en')} per search |`,
    '',
    `Search mode cuts the standing tool context by **${(fullBytes / searchBytes).toFixed(0)}×**. A turn that needs one search carries about ${tokens(searchBytes + avg5).toLocaleString('en')} tokens of tool context instead of ${tokens(fullBytes).toLocaleString('en')}.`,
    '',
    '## Does search find the right tool?',
    '',
    `Two task sets: **dev** (${results.dev.bm25.length} tasks, \`tool-search.jsonl\`), used while tuning the ranking, and **held-out** (${results.holdout.bm25.length} tasks, \`tool-search.holdout.jsonl\`), written before any tuning and only ever looked at in aggregate. ` +
      'A task is a hit at *k* when an acceptable tool is in the top *k*; tasks that don\'t name a store accept that tool on any store. ' +
      `${results.dev.skipped + results.holdout.skipped} tasks skipped (their store isn't provisioned here).`,
    '',
    ...header,
    tableRow('**gateway search**, dev', metrics(results.dev.bm25)),
    tableRow('**gateway search**, held-out', metrics(results.holdout.bm25)),
    tableRow('keyword baseline, dev', metrics(results.dev.kw)),
    tableRow('keyword baseline, held-out', metrics(results.holdout.kw)),
    '',
    'The baseline ranks tools by how many of the query\'s words appear in their name and description: what a quick grep would do.',
    '',
    '**Gateway search on the dev set, by kind of task**',
    '',
    ...header,
    ...groups.map(([label, f]) => tableRow(label, metrics(dev.filter((s) => f(s.task))))),
    '',
    `Search latency through the full MCP path (client → Traefik → gateway → index → client): p50 ${p(0.5)} ms, p95 ${p(0.95)} ms.`,
    '',
    '## How the ranking got here',
    '',
    'The first version was plain BM25 (MiniSearch, name boosted 3×, prefix matching). The eval showed it **losing to the keyword baseline** on the dev set, and the miss list said why: BM25 is blind to the verb. ' +
      '"Start a performance review" scored `create_review`, `update_review` and `delete_review` the same (they share the noun), and ties fell to whichever came first, sometimes a delete.',
    '',
    '| version | dev hit@1 | dev hit@5 | dev MRR | held-out hit@1 | held-out hit@5 | held-out MRR |',
    '|---|---|---|---|---|---|---|',
    '| v1: BM25 | 42% | 77% | 0.55 | 51% | 83% | 0.63 |',
    '| v2: + light stemming, action-aware re-rank, read-before-write | 67% | 79% | 0.72 | 63% | 89% | 0.73 |',
    '| v2, after fixing woo-mcp\'s `sales_summary` description (it returned the average order value without saying so) | 68% | 80% | 0.74 | 63% | 89% | 0.73 |',
    '| v2.1: past-tense questions aren\'t write requests; "how much / total / average" prefers summary tools (found by the e2e suite; its query joined the dev set) | 69% | 81% | 0.74 | 63% | 89% | 0.73 |',
    '',
    'v2 changes, all generic rather than per-query:',
    '- **Stemming** on both sides ("couriers" finds "courier", "scheduled" finds "schedule"), replacing prefix matching.',
    '- **Action-aware re-rank.** Tool names are almost always verb_noun, so each tool\'s verb is read from its name and the query\'s intent from its action words ("add", "start", "set up" → create; "cancel", "mark", "turn off" → update; "remove" → delete; "find" → search). Matching verbs are boosted, mismatched writes demoted.',
    '- **Safe defaults.** Without a write intent, read tools outrank writes and deletes rank last; a record id in the query ("order 77") favours `get_*` over `list_*`.',
    '- Function words ("did", "get", "we") are no longer search terms, so "how many orders did we get" stops matching every `get_*` tool.',
    '',
    `The held-out set moved the same way as the dev set, so these are not tuned to the dev queries. With ${results.holdout.bm25.length} to ${results.dev.bm25.length} tasks, one task is ${(100 / results.dev.bm25.length).toFixed(1)} to ${(100 / results.holdout.bm25.length).toFixed(0)} points: read differences of a few points as noise.`,
    '`apps/gateway/test/search-eval.test.ts` runs this evaluation offline against `catalog.snapshot.json` in CI and fails if either set drops below its floor.',
    '',
    '## Where it still struggles (dev set, not in the top 5)',
    '',
    ...(misses.length ? misses.map((s) => `- "${s.task.q}": wanted ${[...s.expected].slice(0, 3).map((n) => `\`${n}\``).join(' / ')}; got ${s.got.slice(0, 3).map((n) => `\`${n}\``).join(', ') || 'nothing'}`) : ['None.']),
    '',
    'These are vocabulary gaps: "money" vs "revenue", "shop" vs "store", "roll out" vs "deployment", "online" vs "presence". Word matching can\'t bridge them. ' +
      'The next step is hybrid retrieval: embed each tool\'s text once per catalog change and fuse vector ranks with these BM25 ranks (reciprocal rank fusion). BM25 stays in the loop because exact names and identifiers ("SKU", "A/B") are where embeddings are weakest.',
    '',
    '## Notes',
    '',
    '- Hit@5 matters more than hit@1 in practice: the model reads all five results with their descriptions before picking, and it can search again with other words.',
    '- Search runs after the permission filter, so a member is never shown (and the model never tempted by) a tool they can\'t call.',
    `- Reproduce: \`make eval\` (live, refreshes the snapshot) or \`make eval-offline\` (no cluster needed).`,
    '',
  ].join('\n');
  writeFileSync(join(here, 'RESULTS.md'), md);
  console.log(md);
} finally {
  await Promise.allSettled([full.close(), search.close()]);
  for (const k of [fullKey, searchKey]) await admin.del(`/keys/${k.split('_')[1]}`);
}
